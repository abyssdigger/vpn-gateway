HOST_INTERFACE = "host0"


@dataclass(frozen=True)
class FirewallDesiredState:
    restore_text: str
    canonical_save: str


def normalize_iptables_save(text: str) -> str:
    """Normalize iptables-save/restore representation for semantic comparison.

    The kernel/save path may:
    - emit packet/byte counters on rule lines when -c is used;
    - reorder comma-separated conntrack states;
    - group all rules by chain even when restore input interleaved chains.

    Rule order *within one chain* remains significant and is preserved.
    """

    table_name: str | None = None
    declarations: list[str] = []
    declaration_order: list[str] = []
    rules_by_chain: dict[str, list[str]] = {}
    other: list[str] = []

    for raw in text.splitlines():
        if raw.startswith("# Generated by") or raw.startswith("# Completed on"):
            continue

        line = raw.strip()
        if not line:
            continue

        if line in {"*filter", "*nat"}:
            table_name = line
            continue

        line = re.sub(r"^\[[0-9]+:[0-9]+\]\s+", "", line)
        line = re.sub(r"\[[0-9]+:[0-9]+\]", "[0:0]", line)

        def normalize_states(match: re.Match[str]) -> str:
            states = sorted(match.group(1).split(","))
            return "--ctstate " + ",".join(states)

        line = re.sub(
            r"--ctstate\s+([A-Z]+(?:,[A-Z]+)*)",
            normalize_states,
            line,
        )

        if line.startswith(":"):
            chain = line[1:].split(maxsplit=1)[0]
            declarations.append(line)
            declaration_order.append(chain)
            rules_by_chain.setdefault(chain, [])
            continue

        if line.startswith("-A "):
            parts = line.split(maxsplit=2)
            if len(parts) < 3:
                other.append(line)
                continue
            chain = parts[1]
            rules_by_chain.setdefault(chain, []).append(line)
            if chain not in declaration_order:
                declaration_order.append(chain)
            continue

        if line == "COMMIT":
            continue

        other.append(line)

    normalized: list[str] = []
    if declarations:
        if table_name is None:
            raise ValueError("iptables serialization has chain declarations without table")
        normalized.append(table_name)
        normalized.extend(declarations)
        for chain in declaration_order:
            normalized.extend(rules_by_chain.get(chain, ()))
        normalized.extend(other)
        normalized.append("COMMIT")
    else:
        normalized.extend(other)

    return "\n".join(normalized).strip()

def _forward_state_rule(
    *,
    ingress: str,
    egress: str,
    state: str,
    verdict: str,
    source: str | None = None,
    destination: str | None = None,
) -> str:
    parts = ["-A", "FORWARD"]
    if source is not None:
        parts.extend(["-s", source])
    if destination is not None:
        parts.extend(["-d", destination])
    parts.extend(["-i", ingress, "-o", egress])
    parts.extend(["-m", "conntrack", "--ctstate", state, "-j", verdict])
    return " ".join(parts)

def _port_text(port_range: PortRange) -> str:
    if port_range.start == port_range.end:
        return str(port_range.start)
    return f"{port_range.start}:{port_range.end}"


def _envelope_rule_lines(
    chain: str,
    rule: TrafficEnvelopeRule,
) -> tuple[str, ...]:
    sources = rule.source_ports or (None,)
    destinations = rule.destination_ports or (None,)
    verdict = (
        "RETURN"
        if rule.action is EnvelopeAction.ALLOW
        else "DROP"
    )

    lines: list[str] = []
    for source_port in sources:
        for destination_port in destinations:
            parts = ["-A", chain]
            if rule.source is not None:
                parts.extend(["-s", rule.source.with_prefixlen])
            if rule.destination is not None:
                parts.extend(["-d", rule.destination.with_prefixlen])
            if rule.protocol is not EnvelopeProtocol.ANY:
                parts.extend(["-p", rule.protocol.value])
                if rule.protocol in {
                    EnvelopeProtocol.TCP,
                    EnvelopeProtocol.UDP,
                }:
                    parts.extend(["-m", rule.protocol.value])
            if source_port is not None:
                parts.extend(["--sport", _port_text(source_port)])
            if destination_port is not None:
                parts.extend(["--dport", _port_text(destination_port)])
            parts.extend(["-j", verdict])
            lines.append(" ".join(parts))
    return tuple(lines)


def _envelope_chains(
    config: ActiveConfig,
) -> dict[str, tuple[str, str]]:
    device_names = [
        name
        for name in sorted(config.active_device_names)
        if config.devices[name].traffic_envelope is not None
    ]
    return {
        device_name: (
            f"VPNG-E{index}-F",
            f"VPNG-E{index}-T",
        )
        for index, device_name in enumerate(device_names, start=1)
    }



def _publication_input_lines(
    config: ActiveConfig,
    local_address: IPv4Address | None,
) -> tuple[str, ...]:
    endpoints: set[tuple[str, int, int]] = set()
    for device_name in sorted(config.active_device_names):
        for publication in config.devices[device_name].publications:
            endpoints.add(
                (
                    publication.protocol.value,
                    publication.internal.start,
                    publication.internal.end,
                )
            )

    if endpoints and local_address is None:
        raise ValueError(
            "active publications require the ROU-local publication address "
            "for INPUT materialization"
        )

    if local_address is None:
        return ()

    lines: list[str] = []
    for protocol, start, end in sorted(endpoints):
        port = str(start) if start == end else f"{start}:{end}"
        lines.append(
            f"-A INPUT -d {local_address}/32 -i {HOST_INTERFACE} "
            f"-p {protocol} -m {protocol} --dport {port} "
            "-m conntrack --ctstate NEW -j ACCEPT"
        )
    return tuple(lines)


def compile_filter_state(
    config: ActiveConfig,
    bindings: DeviceBindingSnapshot,
    *,
    local_publication_address: IPv4Address | None = None,
) -> FirewallDesiredState:
    """Compile the complete ROU-owned IPv4 filter table.

    INPUT/FORWARD/OUTPUT are all default-DROP.

    INPUT admits loopback, host0 return traffic for locally originated connections, and
    host0 NEW traffic only to configured internal publication endpoints. Device interfaces
    have no local INPUT admission.

    OUTPUT admits loopback plus local traffic whose egress is host0. There is no implicit
    local OUTPUT through Device interfaces.

    Device-envelope chains are traversed before any generated FORWARD state/profile
    acceptance. Envelope allow returns to FORWARD; it never accepts traffic directly.
    ESTABLISHED/RELATED FORWARD acceptance is scoped to currently bound Device interfaces.
    """

    chains = _envelope_chains(config)

    lines = [
        "*filter",
        ":INPUT DROP [0:0]",
        ":FORWARD DROP [0:0]",
        ":OUTPUT DROP [0:0]",
    ]
    for from_chain, to_chain in chains.values():
        lines.append(f":{from_chain} - [0:0]")
        lines.append(f":{to_chain} - [0:0]")

    lines.extend(
        [
            "-A INPUT -m conntrack --ctstate INVALID -j DROP",
            "-A INPUT -i lo -j ACCEPT",
            f"-A INPUT -i {HOST_INTERFACE} -m conntrack "
            "--ctstate ESTABLISHED,RELATED -j ACCEPT",
        ]
    )
    lines.extend(
        _publication_input_lines(
            config,
            local_publication_address,
        )
    )

    lines.extend(
        [
            "-A OUTPUT -m conntrack --ctstate INVALID -j DROP",
            "-A OUTPUT -o lo -j ACCEPT",
            f"-A OUTPUT -o {HOST_INTERFACE} -m conntrack "
            "--ctstate ESTABLISHED,RELATED -j ACCEPT",
            f"-A OUTPUT -o {HOST_INTERFACE} -m conntrack "
            "--ctstate NEW -j ACCEPT",
            "-A FORWARD -m conntrack --ctstate INVALID -j DROP",
        ]
    )

    by_device = bindings.by_device

    # Device envelope is cumulative with Profile policy and must precede every ACCEPT.
    for device_name in sorted(chains):
        from_chain, to_chain = chains[device_name]
        for binding in by_device.get(device_name, ()):
            ifname = binding.identity.ifname
            lines.append(
                f"-A FORWARD -i {HOST_INTERFACE} -o {ifname} -j {to_chain}"
            )
            lines.append(
                f"-A FORWARD -i {ifname} -o {HOST_INTERFACE} -j {from_chain}"
            )

    seen_ifnames: set[str] = set()
    for binding in bindings.bound:
        ifname = binding.identity.ifname
        if ifname in seen_ifnames:
            continue
        seen_ifnames.add(ifname)
        lines.append(
            _forward_state_rule(
                ingress=HOST_INTERFACE,
                egress=ifname,
                state="ESTABLISHED,RELATED",
                verdict="ACCEPT",
            )
        )
        lines.append(
            _forward_state_rule(
                ingress=ifname,
                egress=HOST_INTERFACE,
                state="ESTABLISHED,RELATED",
                verdict="ACCEPT",
            )
        )

    for intent in compile_new_flow_intents(config):
        for binding in by_device.get(intent.device_name, ()):
            prefix = intent.remote_prefix.with_prefixlen
            verdict = intent.verdict.value.upper()

            if intent.direction is FlowDirection.HOST_TO_DEVICE:
                lines.append(
                    _forward_state_rule(
                        ingress=HOST_INTERFACE,
                        egress=binding.identity.ifname,
                        destination=prefix,
                        state="NEW",
                        verdict=verdict,
                    )
                )
            else:
                lines.append(
                    _forward_state_rule(
                        ingress=binding.identity.ifname,
                        egress=HOST_INTERFACE,
                        source=prefix,
                        state="NEW",
                        verdict=verdict,
                    )
                )

    # User-defined chains may be serialized after callers; their jump position above
    # determines evaluation order, not their textual definition position.
    for device_name in sorted(chains):
        envelope = config.devices[device_name].traffic_envelope
        if envelope is None:
            raise ValueError(
                f"missing traffic envelope for compiled chain Device {device_name!r}"
            )
        from_chain, to_chain = chains[device_name]

        for rule in envelope.rules:
            if rule.direction is EnvelopeDirection.FROM_DEVICE:
                lines.extend(_envelope_rule_lines(from_chain, rule))
            else:
                lines.extend(_envelope_rule_lines(to_chain, rule))

        terminal = (
            "RETURN"
            if envelope.default_action is EnvelopeAction.ALLOW
            else "DROP"
        )
        lines.append(f"-A {from_chain} -j {terminal}")
        lines.append(f"-A {to_chain} -j {terminal}")

    lines.extend(["COMMIT", ""])
    restore_text = "\n".join(lines)
    return FirewallDesiredState(
        restore_text=restore_text,
        canonical_save=normalize_iptables_save(restore_text),
    )
