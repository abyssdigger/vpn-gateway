from pathlib import Path
import sys
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from rou.command_backend import CommandResult, NamespaceBackend
from rou.firewall_kernel import apply_filter_state, verify_filter_state
from rou.firewall_state import FirewallDesiredState


class FakeHostBackend:
    def __init__(self, save_text):
        self.save_text = save_text
        self.calls = []

    def run(self, argv, *, input_text=None, check=True):
        self.calls.append((argv, input_text))
        if argv[-4:] == ("iptables-legacy-save", "-c", "-t", "filter"):
            stdout = self.save_text
        else:
            stdout = ""
        return CommandResult(argv, 0, stdout, "")


class FirewallKernelTests(unittest.TestCase):
    def test_apply_uses_restore_stdin_inside_namespace(self):
        desired = FirewallDesiredState(
            restore_text="*filter\n:FORWARD DROP [0:0]\nCOMMIT\n",
            canonical_save="*filter\n:FORWARD DROP [0:0]\nCOMMIT",
        )
        host = FakeHostBackend("")
        backend = NamespaceBackend("rou0", host)

        apply_filter_state(desired, backend)

        argv, stdin = host.calls[0]
        self.assertEqual(
            argv,
            ("ip", "netns", "exec", "rou0", "iptables-legacy-restore"),
        )
        self.assertEqual(stdin, desired.restore_text)

    def test_verify_normalizes_counters_and_generator_comments(self):
        desired = FirewallDesiredState(
            restore_text="",
            canonical_save=(
                "*filter\n"
                ":INPUT ACCEPT [0:0]\n"
                ":FORWARD DROP [0:0]\n"
                ":OUTPUT ACCEPT [0:0]\n"
                "COMMIT"
            ),
        )
        host = FakeHostBackend(
            "# Generated by iptables-save\n"
            "*filter\n"
            ":INPUT ACCEPT [12:345]\n"
            ":FORWARD DROP [2:99]\n"
            ":OUTPUT ACCEPT [7:777]\n"
            "COMMIT\n"
            "# Completed on now\n"
        )
        result = verify_filter_state(desired, NamespaceBackend("rou0", host))
        self.assertTrue(result.ok, (result.actual, result.expected))

    def test_verify_detects_rule_drift(self):
        desired = FirewallDesiredState(
            restore_text="",
            canonical_save="*filter\n:FORWARD DROP [0:0]\nCOMMIT",
        )
        host = FakeHostBackend(
            "*filter\n:FORWARD ACCEPT [0:0]\nCOMMIT\n"
        )
        result = verify_filter_state(desired, NamespaceBackend("rou0", host))
        self.assertFalse(result.ok)


if __name__ == "__main__":
    unittest.main()
